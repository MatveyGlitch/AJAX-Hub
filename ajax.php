$news = [];

foreach ($newsData as $index => $entry) {
    $news[] = [
        'id' => $index + 1,
        'title' => $entry[0],
        'preview' => $entry[1],
        'content' => $entry[2],
        'date' => date('Y-m-d', strtotime('2026-11-01 +' . $index . ' days'))
    ];
}


// ===== ВЫБОР ТИПА ДАННЫХ =====

switch ($type) {
    case 'nickname':
        $items = $nicknames;
        $defaultLimit = 10;
        break;

    case 'news':
        $items = $news;
        $defaultLimit = 5;
        break;

    default:
        http_response_code(400);

        echo json_encode([
            'success' => false,
            'error' => 'Неизвестный тип запроса. Используйте nickname или news.'
        ], JSON_UNESCAPED_UNICODE);

        exit;
}


// ===== ПОЛУЧЕНИЕ ОДНОЙ НОВОСТИ =====

if ($type === 'news' && isset($input['id'])) {
    $id = (int) $input['id'];

    foreach ($news as $item) {
        if ($item['id'] === $id) {
            echo json_encode([
                'success' => true,
                'item' => $item
            ], JSON_UNESCAPED_UNICODE);

            exit;
        }
    }

    http_response_code(404);

    echo json_encode([
        'success' => false,
        'error' => 'Новость не найдена.'
    ], JSON_UNESCAPED_UNICODE);

    exit;
}


// ===== ПОИСК ПО НЕСКОЛЬКИМ СЛОВАМ =====

$query = trim((string) ($input['query'] ?? ''));

if ($query !== '') {
    $words = preg_split('/\s+/u', $query, -1, PREG_SPLIT_NO_EMPTY);

    $items = array_values(array_filter($items, function ($item) use ($words) {

        $text = implode(' ', array_map('strval', $item));

        foreach ($words as $word) {
            $pattern = '/' . preg_quote($word, '/') . '/iu';

            if (!preg_match($pattern, $text)) {
                return false;
            }
        }

        return true;
    }));
}


// ===== СОРТИРОВКА =====

$sort = $input['sort'] ?? 'asc';

if ($sort === 'asc' || $sort === 'desc') {
    $field = $type === 'nickname' ? 'nickname' : 'title';

    usort($items, function ($a, $b) use ($sort, $field) {
        $result = strcmp($a[$field], $b[$field]);

        return $sort === 'asc' ? $result : -$result;
    });
}


// ===== ПОСТРАНИЧНАЯ ЗАГРУЗКА =====

$total = count($items);
$offset = max(0, (int) ($input['offset'] ?? 0));
$limit = max(1, min(50, (int) ($input['limit'] ?? $defaultLimit)));

$pageItems = array_slice($items, $offset, $limit);


// ===== ОТВЕТ СЕРВЕРА =====

echo json_encode([
    'success' => true,
    'type' => $type,
    'total' => $total,
    'offset' => $offset,
    'limit' => $limit,
    'items' => $pageItems
], JSON_UNESCAPED_UNICODE | JSON_PRETTY_PRINT);